import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export async function upgradeSql() {
  let sql = `-- Generated by scripts/prepare-upgrade.mjs. Run as database owner in Supabase SQL Editor.
-- Upgrades 008 or 009 to 010; repeating on 010 is harmless. Does not enable payments.
-- Both migrations and their history records commit together; no reset or data deletion.
BEGIN;
SELECT pg_advisory_xact_lock(20261102, 10);
`;
  for (const [version, previous, name] of [
    ['202611020009', '202611020008', 'stars'],
    ['202611020010', '202611020009', 'admin'],
  ]) {
    const original = await readFile(
      `supabase/migrations/${version}_${name}.sql`,
      'utf8',
    );
    const body = original
      .trim()
      .replace(/^BEGIN;/, '')
      .replace(/COMMIT;$/, '');
    sql += `
DO $upgrade_${name}$
DECLARE current_version text;
BEGIN
  current_version := public.voklumi_database_status()->>'schemaVersion';
  IF current_version = '${previous}' THEN
    EXECUTE $migration_${name}$${body}$migration_${name}$;
  ELSIF current_version NOT IN ('${version}', '202611020010') OR current_version IS NULL THEN
    RAISE EXCEPTION 'Unexpected database version; use ordered migrations instead';
  END IF;
  IF to_regclass('supabase_migrations.schema_migrations') IS NOT NULL THEN
    INSERT INTO supabase_migrations.schema_migrations(version,name,statements)
      VALUES ('${version}','${name}',ARRAY[]::text[]) ON CONFLICT(version) DO NOTHING;
  END IF;
END;
$upgrade_${name}$;
`;
  }
  sql += `
DO $verify$
BEGIN
  IF NOT coalesce((public.voklumi_database_status()->>'ready')::boolean, false) THEN
    RAISE EXCEPTION 'Database readiness failed; upgrade rolled back';
  END IF;
END;
$verify$;
COMMIT;
SELECT public.voklumi_database_status();
`;
  return sql;
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await writeFile('supabase/manual-upgrade-008-010.sql', await upgradeSql());
  console.log(
    'Prepared supabase/manual-upgrade-008-010.sql. No database connection or changes performed.',
  );
}
